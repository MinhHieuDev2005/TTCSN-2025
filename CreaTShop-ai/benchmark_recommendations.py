import argparse
import hashlib
import json
import math
import random
import subprocess
from pathlib import Path

from evaluate_search import metrics
from server import DIMENSIONS, REVISION, VERSION


def dataset():
    randomizer = random.Random(20261120)
    groups = ("Men running shoes for jogging", "Women office loafers for work",
              "Men beach sandals for summer", "Women ankle boots for winter")
    products = []
    for group, title in enumerate(groups):
        for variant in range(12):
            products.append({"id": len(products) + 1, "group": group,
                             "text": f"SYNTHETIC FIXTURE. {title}. Color {('black', 'white', 'blue')[variant % 3]}. Model {variant + 1}.",
                             "stock": 0 if variant == 11 else 10})
    users = []
    for index in range(48):
        group = (0 if index < 20 else 1 if index < 30 else 2 if index < 36 else 3)
        candidates = [product["id"] for product in products if product["group"] == group and product["stock"] > 0]
        history = randomizer.sample(candidates, 2)
        targets = randomizer.sample([product for product in candidates if product not in history], 2)
        cold = index >= 40
        events = [] if cold else [{"product": history[0], "kind": "DELIVERED", "day": -20},
                                 {"product": history[1], "kind": "VIEW", "day": -2}]
        if not cold and index % 3 == 0:
            events.append({"product": history[1], "kind": "CART", "day": 0})
        users.append({"id": f"synthetic-{index + 1:03d}", "coldStart": cold,
                      "train": events, "heldout": [{"product": product, "day": 7} for product in targets]})
    return {"provenance": {"source": "fully-synthetic", "humanReviewed": False, "seed": 20261120,
                           "cutoff": "2026-11-01T00:00:00Z", "dayUnit": "days relative to cutoff",
                           "limitations": "Preferences and future targets are generated by category membership, not observed purchases. Not a human or unbiased recommendation-quality experiment."},
            "products": products, "users": users}


def signals(events):
    weights, latest = {}, {}
    for event in events:
        if event["kind"] == "VIEW" and -90 <= event["day"] <= 0:
            latest[event["product"]] = max(latest.get(event["product"], -90), event["day"])
    for product, day in latest.items():
        weights[product] = math.exp(day / 30)
    for kind, weight, window in (("CART", 3, 0), ("DELIVERED", 5, 180)):
        for product in {event["product"] for event in events if event["kind"] == kind and -window <= event["day"] <= 0}:
            weights[product] = weights.get(product, 0) + weight
    return weights


def cosine(left, right):
    norm = math.sqrt(sum(value * value for value in left) * sum(value * value for value in right))
    return sum(a * b for a, b in zip(left, right)) / norm if norm else 0


def rank(products, vectors, events, popular, personalized=True):
    profile = [0.0] * len(next(iter(vectors.values())))
    if personalized:
        for product, weight in signals(events).items():
            if product in vectors:
                profile = [old + value * weight for old, value in zip(profile, vectors[product])]
    active = any(profile)
    candidates = [product for product in products if product["stock"] > 0 and (not active or product["id"] in vectors)]
    return [product["id"] for product in sorted(candidates, key=lambda product:
            (cosine(profile, vectors[product["id"]]) if active else popular.get(product["id"], 0), product["id"]), reverse=True)]


def evaluate(data, vectors):
    expected = {product["id"] for product in data["products"]}
    if set(vectors) != expected or any(len(vector) != DIMENSIONS or not all(math.isfinite(value) for value in vector)
                                      or not any(vector) for vector in vectors.values()):
        raise ValueError("Invalid or incomplete embeddings")
    popular = {}
    for user in data["users"]:
        for event in user["train"]:
            if event["kind"] == "DELIVERED" and -90 <= event["day"] <= 0:
                popular[event["product"]] = popular.get(event["product"], 0) + 1
    details = []
    for user in data["users"]:
        if any(event["day"] > 0 for event in user["train"]) or any(event["day"] <= 0 for event in user["heldout"]):
            raise ValueError("Temporal leakage in synthetic split")
        available = {product["id"] for product in data["products"] if product["stock"] > 0}
        targets = {event["product"] for event in user["heldout"]}
        if not targets <= available:
            raise ValueError("Unavailable held-out target")
        judgments = {str(product): int(product in targets) for product in available}
        for method in ("personalized", "popular"):
            ranked = rank(data["products"], vectors, user["train"], popular, method == "personalized")
            for cutoff in (5, 10):
                details.append({"user": user["id"], "coldStart": user["coldStart"], "method": method,
                                "cutoff": cutoff, "ids": ranked[:cutoff],
                                **metrics(ranked, judgments, cutoff, True)})
    summary = []
    for cohort in ("warm", "cold"):
        for method in ("personalized", "popular"):
            for cutoff in (5, 10):
                rows = [row for row in details if row["coldStart"] == (cohort == "cold")
                        and row["method"] == method and row["cutoff"] == cutoff]
                summary.append({"cohort": cohort, "method": method, "cutoff": cutoff, "users": len(rows),
                                **{key: sum(row[key] for row in rows) / len(rows) for key in ("precision", "recall", "ndcg")}})
    return {"provenance": data["provenance"], "modelVersion": VERSION, "modelRevision": REVISION,
            "implementation": "Offline reference of production weights/cosine/stock filtering/tie-break, not calls to production recommendations endpoint. Cart is cutoff snapshot; synthetic delivery time is known. Previously seen products remain candidates, matching live behavior.",
            "summary": summary, "perUser": details,
            "limitations": "Generated category-aligned preferences favor content-based matching by construction. No real user outcomes, no tuning, confidence/significance or production effectiveness claim. Cold-start cohort is skewed to the last group by this fixed generator; do not compare warm and cold as equivalent populations."}


def encode(products):
    inspect = subprocess.run(["docker", "inspect", "creatshop-docker-test-embeddings-1"], check=True,
                             capture_output=True, text=True, timeout=20)
    container = json.loads(inspect.stdout)[0]
    if container["Config"]["Labels"].get("com.docker.compose.project") != "creatshop-docker-test":
        raise ValueError("Not the isolated model container")
    helper = "import sys,json,urllib.request; body=sys.stdin.buffer.read(); req=urllib.request.Request('http://127.0.0.1:8001/embed',data=body,headers={'Content-Type':'application/json'}); print(urllib.request.urlopen(req,timeout=90).read().decode())"
    vectors = {}
    for offset in range(0, len(products), 16):
        batch = products[offset:offset + 16]
        result = subprocess.run(["docker", "exec", "-i", container["Id"], "python", "-c", helper],
                                input=json.dumps({"kind": "passage", "texts": [product["text"] for product in batch]}),
                                text=True, capture_output=True, timeout=100, check=True)
        encoded = json.loads(result.stdout)
        if encoded.get("modelVersion") != VERSION or len(encoded["vectors"]) != len(batch):
            raise ValueError("Model version/count mismatch")
        vectors.update({product["id"]: vector for product, vector in zip(batch, encoded["vectors"])})
    return vectors


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Synthetic chronological recommendation benchmark using isolated real embeddings; no database writes")
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    if args.output.exists():
        raise FileExistsError("Refusing to overwrite evidence")
    data = dataset()
    vectors = encode(data["products"])
    report = evaluate(data, vectors)
    args.output.mkdir(parents=True)
    for name, payload in (("dataset.json", data), ("vectors.json", {str(key): value for key, value in vectors.items()}), ("results.json", report)):
        (args.output / name).write_text(json.dumps(payload, indent=2, allow_nan=False), encoding="utf-8")
    checksums = {path.name: hashlib.sha256(path.read_bytes()).hexdigest() for path in args.output.iterdir()}
    (args.output / "checksums.json").write_text(json.dumps(checksums, indent=2), encoding="utf-8")
    print(json.dumps(report["summary"], indent=2))
